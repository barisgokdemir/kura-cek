// Türkçe heceleme: her hecede bir ünlü vardır. İki ünlü arasındaki tek ünsüz
// sonraki heceye, birden çok ünsüzün yalnızca sonuncusu sonraki heceye geçer.
const VOWELS = 'aeıioöuüâîûAEIİOÖUÜÂÎÛ';
const isVowel = (ch) => VOWELS.includes(ch);

export function syllabify(word) {
  const letters = [...word];
  const v = letters.map((ch, i) => (isVowel(ch) ? i : -1)).filter((i) => i >= 0);
  if (v.length <= 1) return [word];
  const cuts = [];
  for (let k = 1; k < v.length; k++) {
    const between = v[k] - v[k - 1] - 1;
    cuts.push(between === 0 ? v[k] : v[k] - 1);
  }
  const out = [];
  let start = 0;
  for (const c of cuts) {
    out.push(letters.slice(start, c).join(''));
    start = c;
  }
  out.push(letters.slice(start).join(''));
  return out;
}

// Bir satırı hecelere böler; noktalama heceye yapışık kalır, sayılmaz.
export function syllablesOf(line) {
  return line
    .split(/\s+/)
    .filter((word) => /\p{L}/u.test(word))
    .flatMap(splitKeeping);
}

// Hece sınırlarını harf dizisi üzerinden bulup orijinal yazımı (kesme, virgül) korur.
function splitKeeping(word) {
  const letters = [...word];
  const idx = letters.map((ch, i) => (/\p{L}/u.test(ch) ? i : -1)).filter((i) => i >= 0);
  const plain = idx.map((i) => letters[i]).join('');
  const parts = syllabify(plain);
  if (parts.length === 1) return [word];
  const out = [];
  let from = 0;
  let k = 0;
  for (let p = 0; p < parts.length; p++) {
    k += [...parts[p]].length;
    const endLetter = p === parts.length - 1 ? letters.length : idx[k];
    out.push(letters.slice(from, endLetter).join(''));
    from = endLetter;
  }
  return out;
}
